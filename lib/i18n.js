function getLang() {
  try {
    const saved = JSON.parse(localStorage.getItem('pm_profile') || '{}').language;
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch (e) {}
  const device = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return TRANSLATIONS[device] ? device : 'en';
}

/* Named tr(), not t() - this codebase uses `t` everywhere as the loop
   variable for "trip" (.map(t => ...), etc.), which would silently
   shadow a global t() the moment a translation call happened inside
   one of those callbacks (exactly what broke the dashboard: t is not
   a function, thrown mid-render, halting everything after it).
   vars: optional {name: 'Alex'} map - substitutes {name} placeholders
   in the translated string. Word order around the placeholder is part
   of each language's own translation, not fixed by the caller, so this
   stays safe to use once more languages exist. */
function tr(key, vars) {
  const lang = getLang();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let str = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.split('{' + k + '}').join(vars[k]); });
  }
  return str;
}

/* One badge-style image per language, shown briefly by
   showLangSwitchSplash() below when the person switches languages.
   A language with no entry here just skips the splash and reloads
   immediately - never a hard requirement to add one. */
const LANG_SPLASH_IMAGES = { en: 'img/lang-en.png', es: 'img/lang-es.png', uk: 'img/lang-uk.png' };

function showLangSwitchSplash(lang) {
  return new Promise((resolve) => {
    const src = LANG_SPLASH_IMAGES[lang];
    if (!src || typeof document === 'undefined' || !document.body) { resolve(); return; }
    const overlay = document.createElement('div');
    overlay.style.cssText = 'position:fixed;inset:0;z-index:999999;background:#fff;display:flex;align-items:center;justify-content:center;opacity:0;transition:opacity 0.4s ease;';
    const img = document.createElement('img');
    img.alt = '';
    img.style.cssText = 'width:200px;height:200px;object-fit:contain;transform:scale(0.85);opacity:0;transition:transform 0.5s cubic-bezier(0.22,1,0.36,1),opacity 0.5s ease;';
    overlay.appendChild(img);
    document.body.appendChild(overlay);
    let started = false;
    const start = () => {
      if (started) return;
      started = true;
      requestAnimationFrame(() => {
        overlay.style.opacity = '1';
        img.style.transform = 'scale(1)';
        img.style.opacity = '1';
      });
      setTimeout(() => {
        overlay.style.opacity = '0';
        img.style.transform = 'scale(1.05)';
        setTimeout(() => { overlay.remove(); resolve(); }, 400);
      }, 1500);
    };
    img.onload = start;
    img.onerror = () => { overlay.remove(); resolve(); };
    img.src = src;
    setTimeout(start, 200); // don't block on a slow/cached-but-unfired load
  });
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  let merged;
  try { merged = { ...JSON.parse(localStorage.getItem('pm_profile') || '{}'), language: lang }; }
  catch (e) { merged = { language: lang }; }
  localStorage.setItem('pm_profile', JSON.stringify(merged));
  /* Same DB.saveProfile() call every other profile field uses (auth.js) -
     harmless no-op server-side today since 'language' isn't a profiles
     column yet; starts syncing automatically the day that column exists,
     no code change needed here. */
  if (typeof DB !== 'undefined' && DB.saveProfile) DB.saveProfile(merged);
  /* window.top, not location: the persistent bottom-nav chrome (and its
     own data-i18n text) lives only in the app-shell's host document
     (lib/app-shell.js) - this page can be running inside one of that
     shell's background tab iframes, where a plain location.reload() would
     refresh only this iframe's content and leave the host's nav bar
     stuck showing whichever language was active at the shell's last cold
     load. Reloading window.top instead re-renders the whole shell,
     nav included; harmless when this already *is* the top level. */
  showLangSwitchSplash(lang).then(() => (window.top || window).location.reload());
}

/* Walks [data-i18n] (textContent) and [data-i18n-attr] (one or more
   "attr:key" pairs, semicolon-separated, e.g. data-i18n-attr="placeholder:profile.hero.namePlaceholder")
   and fills in the current language's strings. Call after any DOM
   this needs to cover is in place (static markup: on load; JS-rendered
   sections: right after they're inserted). */
function applyTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = tr(el.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-attr]').forEach(el => {
    el.getAttribute('data-i18n-attr').split(';').forEach(pair => {
      const idx = pair.indexOf(':');
      if (idx === -1) return;
      const attr = pair.slice(0, idx).trim();
      const key = pair.slice(idx + 1).trim();
      if (attr && key) el.setAttribute(attr, tr(key));
    });
  });
  document.documentElement.lang = getLang();
}
