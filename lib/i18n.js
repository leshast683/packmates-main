/* dictsByLang maps a language code to that language's whole lookup dict
   (e.g. { es: INSPO_DEST_ES, uk: INSPO_DEST_UK }) - keeps every tInspoXxx()
   wrapper below language-count-agnostic; adding a language is just adding
   its dict to the object literal at each call site, no logic changes. */
function _inspoLookup(dictsByLang, value) {
  const dict = dictsByLang[getLang()];
  return (dict && dict[value]) || value;
}
function tInspoDest(value) { return _inspoLookup({ es: INSPO_DEST_ES, uk: INSPO_DEST_UK }, value); }
function tInspoDay(value) { return _inspoLookup({ es: INSPO_DAY_ES, uk: INSPO_DAY_UK }, value); }
function tInspoAct(value) { return _inspoLookup({ es: INSPO_ACT_ES, uk: INSPO_ACT_UK }, value); }
function tInspoCat(value) { return _inspoLookup({ es: INSPO_CAT_ES, uk: INSPO_CAT_UK }, value); }
function tInspoItem(value) { return _inspoLookup({ es: INSPO_ITEM_ES, uk: INSPO_ITEM_UK }, value); }
function tInspoRole(value) { return _inspoLookup({ es: INSPO_ROLE_ES, uk: INSPO_ROLE_UK }, value); }
/* Word for "Day" in each language, used only to rebuild the "Day {n}"
   itinerary label - not a full dict since only one word ever varies. */
const INSPO_DAY_WORD = { es: 'Día', uk: 'День' };
function tInspoDayLabel(value) {
  const word = INSPO_DAY_WORD[getLang()];
  if (!word) return value;
  const m = value.match(/^Day (\d+)$/);
  return m ? word + ' ' + m[1] : value;
}

